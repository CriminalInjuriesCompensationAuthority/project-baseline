import { readdirSync } from 'node:fs';

/**
 * Lists root-level file names in a repo (not directories, excluding noise).
 *
 * @param {string} repoRoot Absolute repo path.
 * @returns {Set<string>} Root file names.
 */
export function rootFiles(repoRoot) {
    const skip = new Set(['node_modules', '.git', 'coverage', 'dist', '.vscode']);
    const names = new Set();
    for (const entry of readdirSync(repoRoot, { withFileTypes: true })) {
        if (entry.isDirectory()) {
            continue;
        }
        if (skip.has(entry.name)) {
            continue;
        }
        names.add(entry.name);
    }
    return names;
}

/**
 * Collects the set of file paths the baseline already manages (from file-policy),
 * so discovery can distinguish "already baselined" from "candidate addition".
 *
 * @param {object} filePolicy Parsed file-policy.yaml.
 * @returns {Set<string>} Baselined paths (as declared, e.g. '.npmrc', '.github/dependabot.yml').
 */
export function baselinedPaths(filePolicy) {
    return new Set((filePolicy.files ?? []).map((f) => f.path));
}

/**
 * Computes a file-frequency matrix across repos and flags candidate baseline additions.
 *
 * @param {object} args
 * @param {Array<{ name: string, dir: string }>} args.repos In-scope repos.
 * @param {Set<string>} args.baselined Paths already managed by the baseline.
 * @param {number} [args.threshold=0.6] Fraction of repos a file must appear in to be a candidate.
 * @returns {{
 *   total: number,
 *   rows: Array<{ file: string, present: number, fraction: number, baselined: boolean, candidate: boolean }>
 * }}
 */
export function discover({ repos, baselined, threshold = 0.6 }) {
    const counts = new Map();
    for (const repo of repos) {
        for (const file of rootFiles(repo.dir)) {
            counts.set(file, (counts.get(file) ?? 0) + 1);
        }
    }

    const total = repos.length;
    const rows = [...counts.entries()]
        .map(([file, present]) => {
            const fraction = total === 0 ? 0 : present / total;
            const isBaselined = baselined.has(file);
            return {
                file,
                present,
                fraction,
                baselined: isBaselined,
                candidate: !isBaselined && fraction >= threshold
            };
        })
        .sort((a, b) => b.present - a.present || a.file.localeCompare(b.file));

    return { total, rows };
}

/**
 * Renders the discovery report as markdown.
 *
 * @param {ReturnType<typeof discover>} result
 * @param {number} [threshold=0.6]
 * @returns {string}
 */
export function renderDiscover(result, threshold = 0.6) {
    const lines = [];
    lines.push('# Shared-file discovery — project-baseline');
    lines.push('');
    lines.push(
        `> Generated by \`baseline discover\` (read-only). ${result.total} in-scope repos; candidate threshold ${Math.round(threshold * 100)}%.`
    );
    lines.push('');

    const candidates = result.rows.filter((r) => r.candidate);
    lines.push('## Candidate baseline additions');
    lines.push('');
    if (candidates.length === 0) {
        lines.push('_None — all high-frequency root files are already baselined._');
    } else {
        lines.push('| File | Present | % | In baseline? |');
        lines.push('| --- | --- | --- | --- |');
        for (const r of candidates) {
            lines.push(
                `| \`${r.file}\` | ${r.present}/${result.total} | ${Math.round(r.fraction * 100)} | no |`
            );
        }
    }
    lines.push('');

    lines.push('## Full frequency matrix');
    lines.push('');
    lines.push('| File | Present | % | Baselined |');
    lines.push('| --- | --- | --- | --- |');
    for (const r of result.rows) {
        lines.push(
            `| \`${r.file}\` | ${r.present}/${result.total} | ${Math.round(r.fraction * 100)} | ${r.baselined ? '✔' : '—'} |`
        );
    }
    lines.push('');

    return `${lines.join('\n')}\n`;
}
