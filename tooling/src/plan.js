/**
 * Resolves the adoption action for a single inspected file from its policy + state.
 *
 * @param {{ state: string, policy: object }} file Inspect result for one file.
 * @returns {'create' | 'replace' | 'merge' | 'manual' | 'leave'} The action to take.
 */
export function resolveAction(file) {
    const { state, policy } = file;
    if (state === 'absent') {
        return policy.whenAbsent ?? 'create';
    }
    if (state === 'present-identical') {
        return 'leave';
    }
    // present-divergent or present-unknown -> use the whenPresent policy.
    return policy.whenPresent ?? 'manual';
}

/**
 * Produces a structured plan from an inspection: each file with its resolved action,
 * applicable migrations, and a summary.
 *
 * @param {import('./inspect.js').inspect extends (...a:any)=>infer R ? R : never} inspection
 * @returns {{
 *   files: Array<{ path: string, state: string, action: string, note?: string }>,
 *   migrations: Array<{ id: string, tracker: string|null, status: string, note?: string }>,
 *   summary: object
 * }}
 */
export function plan(inspection) {
    const files = inspection.files.map((file) => ({
        path: file.path,
        state: file.state,
        action: resolveAction(file),
        note: file.policy.note?.trim()
    }));

    const migrations = inspection.migrations
        .filter((m) => m.applies)
        .map((m) => ({
            id: m.id,
            tracker: m.meta.tracker ?? null,
            status: m.meta.status ?? 'required',
            note: m.meta.note?.trim()
        }));

    const count = (action) => files.filter((f) => f.action === action).length;
    const summary = {
        create: count('create'),
        replace: count('replace'),
        merge: count('merge'),
        manual: count('manual'),
        leave: count('leave'),
        autoApplicable: count('create') + count('replace') + count('merge'),
        migrationsRequired: migrations.filter((m) => m.status === 'required').length,
        migrationsDeferred: migrations.filter((m) => m.status === 'deferred').length
    };

    return {
        repoRoot: inspection.repoRoot,
        profile: inspection.profile,
        files,
        migrations,
        summary
    };
}

const ACTION_MARK = {
    create: '✚ create',
    replace: '♻ replace',
    merge: '⤵ merge',
    manual: '✋ manual',
    leave: '✓ leave'
};

/**
 * Renders a plan as a markdown adoption report.
 *
 * @param {ReturnType<typeof plan>} p
 * @param {{ repoName?: string }} [opts]
 * @returns {string} Markdown.
 */
export function renderMarkdown(p, opts = {}) {
    const name = opts.repoName ?? p.repoRoot;
    const lines = [];

    lines.push(`# Adoption plan — \`${name}\``);
    lines.push('');
    lines.push('> **Generated by `baseline plan` (read-only).** No changes were made to the repo.');
    lines.push('');
    lines.push(`- **Profile:** \`${p.profile}\``);
    lines.push('');

    lines.push('## Summary');
    lines.push('');
    lines.push('| Outcome | Count |');
    lines.push('| --- | --- |');
    lines.push(`| Auto-applicable (create/replace/merge) | ${p.summary.autoApplicable} |`);
    lines.push(`| Manual review (files) | ${p.summary.manual} |`);
    lines.push(`| Leave (already compliant) | ${p.summary.leave} |`);
    lines.push(`| Required migrations | ${p.summary.migrationsRequired} |`);
    lines.push(`| Deferred migrations | ${p.summary.migrationsDeferred} |`);
    lines.push('');

    lines.push('## File plan');
    lines.push('');
    lines.push('| File | State | Action |');
    lines.push('| --- | --- | --- |');
    for (const f of p.files) {
        lines.push(`| \`${f.path}\` | ${f.state} | ${ACTION_MARK[f.action] ?? f.action} |`);
    }
    lines.push('');

    if (p.migrations.length > 0) {
        lines.push('## Migrations');
        lines.push('');
        lines.push('| Migration | Status | Tracker |');
        lines.push('| --- | --- | --- |');
        for (const m of p.migrations) {
            lines.push(`| ${m.id} | ${m.status} | ${m.tracker ?? '—'} |`);
        }
        lines.push('');
    }

    return `${lines.join('\n')}\n`;
}
